package souther.compiler.check;

/**
 * A position published none of what its rules about the strings admit, and its own answer was
 * built.
 *
 * <p>The two together are a reading that gave up on nothing and handed on nothing all the same.
 * Every set a position's answer needs is made while the answer is worked out, so a group of them
 * that cannot be made is a group belonging to a position that was given up on — and where it was,
 * the position already carries what it could not work out and a reader is told about it there.
 *
 * <p><b>Not an ordinary limit, so not swallowed.</b> A pattern larger than a machine may be is
 * something this compiler says out loud and goes on from; this is the reading and the publishing
 * disagreeing about whether the position was answered, and a value that came back with nothing to
 * say for that reason reads exactly like a value whose rules were all read.
 *
 * <p>What to do about one is not written here, because there is nothing to write yet: no path
 * through this compiler produces it. Reaching this is the news — that a reading now drops a set a
 * rule named while building an answer that does not need it — and what a reader of a model should
 * be told about such a position is a question to answer with that path in hand.
 */
final class AStringPublicationNothingAccountsFor extends TheCheckDisagreesWithItself {

    private static final long serialVersionUID = 1L;

    AStringPublicationNothingAccountsFor(FactSubject position) {
        super("the strings at " + position + " were not published and its answer was built");
    }
}
