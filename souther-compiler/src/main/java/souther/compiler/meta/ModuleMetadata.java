package souther.compiler.meta;

import souther.compiler.ast.Ast;
import souther.compiler.check.Sig;
import souther.compiler.check.Type;
import souther.compiler.frontend.CstFrontend;

import java.lang.classfile.Annotation;
import java.lang.classfile.AnnotationElement;
import java.lang.classfile.AnnotationValue;
import java.lang.classfile.ClassFile;
import java.lang.classfile.ClassModel;
import java.lang.classfile.ClassTransform;
import java.lang.classfile.attribute.RuntimeInvisibleAnnotationsAttribute;
import java.lang.constant.ClassDesc;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Writes a module's declarations into the classes it generated, so another project can import the
 * module from a jar without its {@code .sou}.
 *
 * <p>Each definition goes on the class it produced — a {@code data} on the class of that name, a
 * behavior on its interface — as the source that declared it. What is left is module-level: the
 * name, the {@code exposing} list, the imports the declarations were written under, and an index of
 * which classes to read. That goes on a {@code $Module} class emitted for the purpose.
 *
 * <p>This runs over the generated bytes rather than inside the backend: nothing about how a class is
 * built depends on what is being said about it.
 */
public final class ModuleMetadata {

    private ModuleMetadata() {}

    /**
     * The version of the boundary an importing module crosses: the names, descriptors and
     * visibilities it reaches — {@code __construct}, a codec, a behavior's class and methods, an
     * output union's cases, the runtime types in their signatures. A change to any of those makes a
     * previously built jar unusable here, and this number is how that is said rather than guessed.
     * A change confined to the inside of a generated method does not touch it.
     */
    public static final int COMPAT = 1;

    /**
     * The compiler that produced a module, for the message that reports a {@link #COMPAT} mismatch.
     * It comes from the jar's manifest, which Maven fills from the project version — the root pom is
     * the one place the version is written, and a constant here would be another place to forget.
     * Running from class files there is no manifest, and nothing depends on the value.
     */
    public static String compilerVersion() {
        String version = ModuleMetadata.class.getPackage().getImplementationVersion();
        return version == null ? "unreleased" : version;
    }

    private static final ClassDesc MODULE_ANN = ClassDesc.of("souther.runtime.meta.SoutherModule");
    private static final ClassDesc DATA_ANN = ClassDesc.of("souther.runtime.meta.SoutherData");
    private static final ClassDesc BEHAVIOR_ANN = ClassDesc.of("souther.runtime.meta.SoutherBehavior");

    /** The generated {@code $Module} class of {@code moduleName}. */
    public static String moduleClassName(String moduleName) {
        return moduleName + ".$Module";
    }

    /**
     * {@code classes} with each definition's declaration written onto the class it generated, plus
     * the module's own {@code $Module}. {@code sigs} supplies the signature of a {@code >->}
     * composition, which declares stages instead of one; {@code injected} names the behaviors this
     * module leaves to be injected.
     */
    public static void stamp(Map<String, byte[]> out, Ast.Module module,
                             CstFrontend.Slices slices, Map<String, Sig> sigs,
                             Set<String> injected, String compilerVersion) {
        List<String> types = new ArrayList<>();
        for (Ast.Def def : module.defs()) {
            String text = slices.defs().get(def.name());
            if (text == null) {
                continue;   // derived, not declared: nothing was written for it to carry
            }
            types.add(def.name());
            add(out, module.name() + "." + def.name(),
                    Annotation.of(DATA_ANN, AnnotationElement.ofString("value", text)));
        }
        List<String> behaviors = new ArrayList<>();
        for (Ast.BehaviorDef b : module.behaviors()) {
            String signature = signatureOf(b, slices, sigs);
            if (signature == null) {
                continue;
            }
            behaviors.add(b.name());
            add(out, module.name() + "." + behaviorClass(b.name()),
                    Annotation.of(BEHAVIOR_ANN,
                            AnnotationElement.ofString("signature", signature),
                            AnnotationElement.ofBoolean("injected", injected.contains(b.name()))));
        }
        out.put(moduleClassName(module.name()),
                moduleClass(module, slices, types, behaviors, compilerVersion));
    }

    /**
     * What the importing module reads as this behavior's signature. A declared one is the
     * declaration as written. A composition declares its stages, not a signature, so the computed
     * one is written out — the stages are the module's own business and are not carried.
     */
    private static String signatureOf(Ast.BehaviorDef b, CstFrontend.Slices slices,
                                      Map<String, Sig> sigs) {
        if (b instanceof Ast.SpecBehavior) {
            return slices.behaviors().get(b.name());
        }
        Sig sig = sigs.get(b.name());
        if (sig == null) {
            return null;
        }
        StringBuilder params = new StringBuilder();
        for (int i = 0; i < sig.ins().size(); i++) {
            params.append(i == 0 ? "" : ", ").append("in").append(i).append(": ")
                    .append(Type.showQualified(sig.ins().get(i)));
        }
        return "behavior " + b.name() + " : (" + params + ") -> " + Type.showQualified(sig.out());
    }

    /** The class a behavior's interface is emitted under: its name with the first letter capitalized
     * where there is one to capitalize (spec 19.5). */
    private static String behaviorClass(String name) {
        if (name.isEmpty()) {
            return name;
        }
        return Character.toUpperCase(name.charAt(0)) + name.substring(1);
    }

    private static void add(Map<String, byte[]> classes, String binaryName, Annotation annotation) {
        byte[] bytes = classes.get(binaryName);
        if (bytes == null) {
            return;   // no class of that name was generated; nothing to say it on
        }
        ClassFile cf = ClassFile.of();
        ClassModel model = cf.parse(bytes);
        classes.put(binaryName, cf.transformClass(model, ClassTransform.endHandler(
                b -> b.with(RuntimeInvisibleAnnotationsAttribute.of(annotation)))));
    }

    private static byte[] moduleClass(Ast.Module module, CstFrontend.Slices slices,
                                      List<String> types, List<String> behaviors,
                                      String compilerVersion) {
        Annotation annotation = Annotation.of(MODULE_ANN,
                AnnotationElement.ofInt("compat", COMPAT),
                AnnotationElement.ofString("compiler", compilerVersion),
                AnnotationElement.ofString("name", module.name()),
                strings("exposing", module.exposing()),
                strings("imports", slices.imports()),
                strings("types", types),
                strings("behaviors", behaviors),
                strings("invariantHelpers", invariantHelpers(module, slices)));
        return ClassFile.of().build(ClassDesc.of(moduleClassName(module.name())), cb -> cb
                // the same floor every generated class targets, not whichever JDK is building
                .withVersion(ClassFile.JAVA_25_VERSION, 0)
                .withFlags(ClassFile.ACC_FINAL | ClassFile.ACC_SYNTHETIC)
                .with(RuntimeInvisibleAnnotationsAttribute.of(annotation)));
    }

    private static AnnotationElement strings(String name, List<String> values) {
        List<AnnotationValue> elements = new ArrayList<>();
        for (String value : values) {
            elements.add(AnnotationValue.ofString(value));
        }
        return AnnotationElement.of(name, AnnotationValue.ofArray(elements));
    }

    /**
     * The helper {@code let}s the module's invariants call, transitively, as they were written. An
     * invariant is part of what a type is, so it has to be readable where the type is imported, and
     * it cannot be read without the helpers it names. A helper no invariant reaches is not carried:
     * this publishes what the declarations need, not the module's implementation.
     */
    private static List<String> invariantHelpers(Ast.Module module, CstFrontend.Slices slices) {
        Map<String, Ast.FnDef> own = new LinkedHashMap<>();
        for (Ast.FnDef fn : module.fns()) {
            own.put(fn.name(), fn);
        }
        Set<String> reached = new LinkedHashSet<>();
        for (Ast.Def def : module.defs()) {
            if (def instanceof Ast.Data d && d.invariant().isPresent()) {
                reach(d.invariant().get(), own, reached, new HashSet<>());
            }
        }
        List<String> texts = new ArrayList<>();
        for (String name : reached) {
            String text = slices.fns().get(name);
            if (text != null) {
                texts.add(text);
            }
        }
        return texts;
    }

    private static void reach(Ast.Expr e, Map<String, Ast.FnDef> own, Set<String> reached,
                              Set<String> visiting) {
        if (e instanceof Ast.Call call && own.containsKey(call.fn()) && visiting.add(call.fn())) {
            reached.add(call.fn());
            reach(own.get(call.fn()).body(), own, reached, visiting);
        }
        Ast.forEachChild(e, c -> reach(c, own, reached, visiting));
    }
}
