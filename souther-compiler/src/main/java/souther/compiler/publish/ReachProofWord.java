package souther.compiler.publish;

/**
 * What a document calls the place a proof that nothing arrives was about, where a row went there.
 *
 * <p>An enum so that the words the shipped schema names for {@code reachProofsContradicted} are
 * held against something: a word added here has to be taught to the schema before it can be
 * written.
 */
public enum ReachProofWord {

    /** An arm of a fork, proven to be gone into by nothing. */
    ARM,

    /** A comparison coming out one way, proven to come out so for nothing. */
    COMPARISON_OUTCOME,

    /**
     * A construct a line is drawn at — a comparison, or an application whose answer states one —
     * proven to be arrived at by nothing at all.
     */
    ARRIVAL,

    /** A way through a body's decision, proven to be taken by no input. */
    WAY_NO_INPUT_TAKES
}
